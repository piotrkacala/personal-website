function t(lang, key, replacements) {
  let str = (i18n[lang] && i18n[lang][key]) || (i18n.en[key]) || key;
  if (replacements) {
    for (const [k, v] of Object.entries(replacements)) {
      str = str.replace(`{${k}}`, v);
    }
  }
  return str;
}
